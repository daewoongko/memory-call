function toDateKey(month, day) {
  return `2026-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

function buildDiary(month, row, index) {
  const [title, moment, insight, weather] = row.split("|");
  const date = toDateKey(month, index + 1);
  return {
    date,
    image: `/diary/daily/${String(month).padStart(2, "0")}/${date}.webp`,
    title,
    writing: `${moment} ${DIARY_CLOSINGS[index % DIARY_CLOSINGS.length]}`,
    insight,
    weather,
    risk: DEMO_RISKS[date] || null,
  };
}

